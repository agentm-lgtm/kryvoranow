<section id="kvo_sec_season_f8d5">
  <div class="kvo_season_w6j2">
    <div class="kvo_season_img_q3n8" style="background-image:url('https://images.pexels.com/photos/1183266/pexels-photo-1183266.jpeg?auto=compress&cs=tinysrgb&w=1260&h=750&dpr=1')" role="img" aria-label="Autumn season at the workshop"></div>
    <div class="kvo_season_text_m8f5">
      <span class="kvo_eyebrow_u6r8" style="color:var(--kvo-bone)">Current season</span>
      <h3>The Closing Light</h3>
