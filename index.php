<section class="kvo_section_p9h4 kvo_section_dark_y2d9" id="kvo_sec_craft_q8k2">
  <span class="kvo_eyebrow_u6r8">The craft</span>
  <h2 class="kvo_h2_t4q1">Three trades, one roof, no hurry.</h2>
  <p class="kvo_lead_b8j5">Kryvoranow does not separate the maker from the material. The same hands that weave also cut, and the same eyes that judge a dye bath judge a thrown rim. The studio is organised around three connected disciplines.</p>
  <div class="kvo_pillars_q1f3">
    <div class="kvo_pillar_h7d2">
      <div class="kvo_pillar_num_c4m8">Craft 01</div>
      <h3 class="kvo_pillar_h3_v9k6">Clothwork</h3>
      <p class="kvo_pillar_p_j5r2">Cutting, joining and finishing garments from woven wool. Seams are fell-stitched by hand where it matters, and the inside of a coat is given the same care as the outside. A single coat moves through the workshop for the better part of two weeks.</p>
    </div>
    <div class="kvo_pillar_h7d2">
      <div class="kvo_pillar_num_c4m8">Craft 02</div>
      <h3 class="kvo_pillar_h3_v9k6">Weaving</h3>
      <p class="kvo_pillar_p_j5r2">Warping and weaving on a four-shaft floor loom. The warp is sett by hand and the weft is beaten to a density that lets the blanket keep its shape for decades. Irregularities are recorded, not corrected.</p>
    </div>
    <div class="kvo_pillar_h7d2">
      <div class="kvo_pillar_num_c4m8">Craft 03</div>
      <h3 class="kvo_pillar_h3_v9k6">Claywork</h3>
      <p class="kvo_pillar_p_j5r2">Throwing, trimming and firing vessels from local clay. The wood kiln is fired twice a season and the results are sorted by character rather than by perfection. A bowl with a shy rim is still a bowl.</p>
    </div>
  </div>
</section>

