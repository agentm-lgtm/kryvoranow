<section class="kvo_section_p9h4 kvo_section_alt_l3k7" id="kvo_sec_process_r4t6">
  <span class="kvo_eyebrow_u6r8">Process</span>
  <h2 class="kvo_h2_t4q1">How a garment moves through the room.</h2>
  <p class="kvo_lead_b8j5">The same four steps apply, in spirit, to the weaves and the vessels as well. They are written here in the order a coat follows, because a coat is the longest piece the workshop makes.</p>
  <div class="kvo_steps_e8f3">
    <div class="kvo_step_v5m9">
      <div class="kvo_step_num_p2k7">01</div>
      <h3 class="kvo_step_h3_r6t4">Mark and cut</h3>
      <p class="kvo_step_p_c9n8">The cloth is laid on the cutting table under the north light and the pattern is marked in chalk. Cutting is done in a single attentive pass.</p>
    </div>
    <div class="kvo_step_v5m9">
      <div class="kvo_step_num_p2k7">02</div>
      <h3 class="kvo_step_h3_r6t4">Join and fell</h3>
      <p class="kvo_step_p_c9n8">Pieces are joined with a machine seam and then fell-stitched by hand where the strength matters. The interior is given equal attention.</p>
    </div>
    <div class="kvo_step_v5m9">
      <div class="kvo_step_num_p2k7">03</div>
      <h3 class="kvo_step_h3_r6t4">Finish and press</h3>
      <p class="kvo_step_p_c9n8">Edges are finished, buttons of bone are set by hand, and the garment is pressed with a heavy iron. A contrast thread closes the interior pocket.</p>
    </div>
    <div class="kvo_step_v5m9">
      <div class="kvo_step_num_p2k7">04</div>
      <h3 class="kvo_step_h3_r6t4">Inspect and rest</h3>
      <p class="kvo_step_p_c9n8">The piece is inspected under the north window, then left to rest overnight on the form before it is wrapped and made ready.</p>
    </div>
  </div>
</section>

