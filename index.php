  <span class="kvo_eyebrow_u6r8">Manifesto</span>
  <blockquote class="kvo_pullquote_w8e4">
    "We are not interested in making more. We are interested in making things that are still here, and still useful, when the season that made them has long since closed."
    <span class="kvo_pullquote_attr_s6n3">From the workshop notebook, 2003</span>
  </blockquote>
  <p style="max-width:62ch;margin:40px auto 0;text-align:center;color:var(--kvo-slate);font-size:16px;">The manifesto is short because the work is long. Kryvoranow holds to a handful of ideas: source close, make by hand, mend before replacing, charge honestly, and let the slow season set the pace. Everything else is detail.</p>
</section>

