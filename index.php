  <div class="kvo_twocol_m1v6">
    <div class="kvo_twocol_text_o3p2">
      <span class="kvo_eyebrow_u6r8">The atelier</span>
      <h2 class="kvo_h2_t4q1">A room where things are made slowly, on purpose.</h2>
      <p class="kvo_lead_b8j5">We keep the workshop in full view. There is no back of house. The cutting table sits beneath the north window so the light stays honest, and the loom occupies the corner that used to be a coal shed. Visitors are welcome to stand and watch a garment take shape across several afternoons.</p>
      <p>The Kryvoranow workshop was assembled from parts of three older trades: a tailor's cutting table rescued from a closing premises in the valley, a floor loom rebuilt by a neighbour who once made sails, and a single dye vat that has been in continuous use since the first season. Nothing here is new in the way that word is usually meant. Everything has been mended, re-tuned, or carried a distance.</p>
      <p>What leaves the room is the residue of attention. A coat that took eleven days. A set of bowls pulled from local clay and fired in a kiln fired with brushwood. A folded paper good printed on a press that demands a steady hand. The work is not fast, and it is not meant to be.</p>
