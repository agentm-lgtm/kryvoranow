<section class="kvo_section_p9h4 kvo_section_alt_l3k7" id="kvo_sec_history_x3t6">
  <span class="kvo_eyebrow_u6r8">History</span>
  <h2 class="kvo_h2_t4q1">Twenty-six years, told in seasons.</h2>
  <p class="kvo_lead_b8j5">Kryvoranow began as a single cutting table in a borrowed room. The history below is kept brief on purpose; the longer version lives in the workshop notebook, which anyone is welcome to read on a quiet afternoon.</p>
