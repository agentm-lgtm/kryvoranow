      <p class="kvo_tl_p_c4d8">The workshop opens in a back room above a feed store, with a recovered tailor's table, a pair of shears, and the first six coats cut from a single fleece of local wool.</p>
    </div>
    <div class="kvo_tlitem_y9b4">
      <div class="kvo_tl_year_e5m2">2003 &middot; Season Six</div>
      <h3 class="kvo_tl_h3_r7k6">The loom arrives</h3>
      <p class="kvo_tl_p_c4d8">A neighbour donates a disused sailmaker's frame. It is rebuilt into a four-shaft floor loom over the winter, and the first Field Weave blanket is finished on the first warm day of spring.</p>
    </div>
    <div class="kvo_tlitem_y9b4">
      <div class="kvo_tl_year_e5m2">2009 &middot; Season Twelve</div>
      <h3 class="kvo_tl_h3_r7k6">The garden and the dye vat</h3>
      <p class="kvo_tl_p_c4d8">A strip of ground behind the workshop is given over to dye plants. The copper vat, already a decade old, is moved outdoors and fed with rainwater from the new guttering.</p>
    </div>
    <div class="kvo_tlitem_y9b4">
      <div class="kvo_tl_year_e5m2">2014 &middot; Season Seventeen</div>
      <h3 class="kvo_tl_h3_r7k6">Clay enters the room</h3>
      <p class="kvo_tl_p_c4d8">A small kiln is built against the gable wall and the Kiln Vessels line begins. The first firing yields nine usable bowls and a great deal of education.</p>
    </div>
    <div class="kvo_tlitem_y9b4">
      <div class="kvo_tl_year_e5m2">2019 &middot; Season Twenty-Two</div>
      <h3 class="kvo_tl_h3_r7k6">The press and the journal</h3>
      <p class="kvo_tl_p_c4d8">A treadle printing press is rescued and restored. The Paper line and the workshop journal, Field Notes, both begin in the same month.</p>
    </div>
