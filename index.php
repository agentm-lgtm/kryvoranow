<section class="kvo_section_p9h4 kvo_section_dark_y2d9" id="kvo_sec_faq_b9n3">
  <span class="kvo_eyebrow_u6r8">Questions</span>
  <h2 class="kvo_h2_t4q1">Things we are often asked.</h2>
  <div class="kvo_faq_k7n2">
    <details class="kvo_faqitem_x3d6" open>
      <summary>Why does a single garment take nearly two weeks?</summary>
      <p class="kvo_faq_p_v8m2">Because the work is done by hand and in order: cutting, joining, finishing, pressing, and a final inspection under the north light. None of these steps can be safely rushed without the piece losing the quality it was made for. The time is the price of the thing lasting.</p>
    </details>
    <details class="kvo_faqitem_x3d6">
      <summary>Can I visit the workshop while work is in progress?</summary>
      <p class="kvo_faq_p_v8m2">Yes. The room is open to visitors during working hours, and there is no separate viewing area. You are welcome to stand and watch. We only ask that the cutting table be left clear while a garment is being marked.</p>
    </details>
    <details class="kvo_faqitem_x3d6">
      <summary>Do you take on repair and mending of older pieces?</summary>
      <p class="kvo_faq_p_v8m2">We do. A corner of the workshop is set aside for mending, both of our own pieces and of cloth that has come from elsewhere. We prefer visible mends where the structure allows, so the repair becomes part of the object's history.</p>
    </details>
    <details class="kvo_faqitem_x3d6">
      <summary>Where do the wool and the clay come from?</summary>
      <p class="kvo_faq_p_v8m2">The wool comes from two flocks within a short drive of the workshop. The clay is dug from a site within a day's walk. We can tell you the source of any piece in the room, and we keep a written record of each season's materials in the workshop notebook.</p>
    </details>
    <details class="kvo_faqitem_x3d6">
      <summary>Will a dye colour ever be exactly repeated?</summary>
      <p class="kvo_faq_p_v8m2">Not with certainty. The garden pigment changes with the year the plants grew in, the water in the vat, and the weather on the day. We treat this as a feature. If a close match is needed, we will work toward it, but we will not promise it.</p>
    </details>
    <details class="kvo_faqitem_x3d6">
      <summary>How small are the batches, really?</summary>
      <p class="kvo_faq_p_v8m2">Small enough that most lines rarely exceed a dozen pieces in a season, and some consist of a single object. When a line is finished, it is finished. We do not produce to demand; we produce to the material and the season.</p>
    </details>
    <details class="kvo_faqitem_x3d6">
      <summary>Do you ship pieces to visitors who cannot come in person?</summary>
      <p class="kvo_faq_p_v8m2">We do, within reason and within the regions our stockists cover. Arrangements are made by telephone during working hours, and each piece is wrapped in the workshop's own printed paper before it leaves.</p>
    </details>
  </div>
</section>

